using Platform.Core.Abstractions;

namespace Platform.Core.People;

/// <summary>Postgres enum <c>gender</c>.</summary>
public enum Gender
{
    Male,
    Female,
    Unspecified,
}

/// <summary>Postgres enum <c>candidate_source</c>: how a person first reached the agency.</summary>
public enum CandidateSource
{
    Facebook,
    Linkedin,
    Whatsapp,
    Referral,
    JobBoard,
    Other,
}

/// <summary>Postgres enum <c>document_status</c>.</summary>
public enum DocumentStatus
{
    Pending,
    Delivered,
    Validated,
    Rejected,
    Expired,
}

/// <summary>
/// DATA_MODEL §3.6: one row per physical person, shared by recruiting and payroll. Names are stored uppercase as in the
/// client's files; <see cref="FullName"/> is generated by the database in the Excel order (paterno materno nombres).
/// </summary>
public sealed class Person : IStamped, ISoftDeletable
{
    public long Id { get; set; }
    public Guid Uid { get; set; } = Guid.CreateVersion7();
    public required string FirstNames { get; set; }
    public required string LastNamePaternal { get; set; }
    public string? LastNameMaternal { get; set; }
    public string FullName { get; private set; } = "";
    public DateOnly? BirthDate { get; set; }
    public string? BirthState { get; set; }
    public Gender Gender { get; set; } = Gender.Unspecified;
    public bool IsForeign { get; set; }
    public string? Curp { get; set; }
    public string? Rfc { get; set; }
    public string? Nss { get; set; }
    public string? MobilePhone { get; set; }
    public string? Email { get; set; }
    public string? Street { get; set; }
    public string? ExtNumber { get; set; }
    public string? Neighborhood { get; set; }
    public string? PostalCode { get; set; }
    public string? Municipality { get; set; }
    public string? State { get; set; }
    public CandidateSource? Source { get; set; }
    public string? Notes { get; set; }
    /// <summary>When the person accepted the aviso de privacidad in the Candidates app (ARCHITECTURE §6, PLAN D77).</summary>
    public DateTimeOffset? PrivacyNoticeAcceptedAt { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }

    public DateTimeOffset CreatedAt { get; set; }
    public Guid? CreatedBy { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
    public Guid? UpdatedBy { get; set; }
}

/// <summary>
/// DATA_MODEL §3.10. A re-upload is a new row; the previous one points to it through <see cref="SupersededBy"/>, so the
/// current document of a type is the one with <c>superseded_by IS NULL</c>.
/// </summary>
public sealed class PersonDocument : IStamped
{
    public long Id { get; set; }
    public Guid Uid { get; set; } = Guid.CreateVersion7();
    public Guid PersonId { get; set; }
    public Guid DocumentTypeId { get; set; }
    public DocumentStatus Status { get; set; } = DocumentStatus.Delivered;
    public required string StorageKey { get; set; }
    public required string OriginalFilename { get; set; }
    public required string ContentType { get; set; }
    public long SizeBytes { get; set; }
    public DateOnly? IssuedAt { get; set; }
    public DateOnly? ExpiresAt { get; set; }
    public Guid? ValidatedBy { get; set; }
    public DateTimeOffset? ValidatedAt { get; set; }
    public string? RejectionReason { get; set; }
    public int Version { get; set; } = 1;
    public Guid? SupersededBy { get; set; }

    public DateTimeOffset CreatedAt { get; set; }
    public Guid? CreatedBy { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
    public Guid? UpdatedBy { get; set; }
}
