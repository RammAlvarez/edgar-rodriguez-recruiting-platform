// npm run generate:api-types — builds platform-api with OpenAPI generation on, then turns
// libs/shared/openapi/platform-api.json into libs/shared/src/generated/api.ts.
// The C# DTOs are the only source of shapes; this file is never edited by hand (CI checks for a diff).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const spec = resolve(root, 'libs/shared/openapi/platform-api.json');
const out = resolve(root, 'libs/shared/src/generated/api.ts');

if (!process.argv.includes('--skip-build')) {
  execFileSync(
    'dotnet',
    ['build', 'services/platform-api/src/Platform.Api', '-p:OpenApiGenerateDocuments=true', '-v', 'q', '-nologo'],
    { cwd: root, stdio: 'inherit' },
  );
}

const DATE_TIME = ts.factory.createTypeReferenceNode('Date');
const BRANDED = (name) => ts.factory.createTypeReferenceNode(name);

const ast = await openapiTS(JSON.parse(readFileSync(spec, 'utf8')), {
  rootTypes: true,
  rootTypesNoSchemaPrefix: true,
  exportType: true,
  // Timestamps are revived to Date by libs/api-client; business dates (format: date, yyyy-MM-dd) stay strings,
  // decimals stay strings (PLAN D46, D55).
  transform(schema) {
    const nullable = Array.isArray(schema.type) && schema.type.includes('null');
    const wrap = (node) =>
      nullable
        ? ts.factory.createUnionTypeNode([node, ts.factory.createLiteralTypeNode(ts.factory.createNull())])
        : node;
    if (schema.format === 'date-time') return wrap(DATE_TIME);
    if (schema.format === 'decimal') return wrap(BRANDED('Decimal'));
    if (schema.format === 'date') return wrap(BRANDED('DateKey'));
    return undefined;
  },
});

const header = `/* eslint-disable */
// GENERATED by libs/shared/scripts/generate-api-types.mjs from the platform-api OpenAPI document. Do not edit.
import type { Decimal, DateKey } from '../wire';
`;
writeFileSync(out, header + astToString(ast));
console.log(`wrote ${out}`);
